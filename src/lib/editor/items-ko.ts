export function itemNameKo(id: string): string {
  const key = (id || "").trim().toUpperCase();
  return ITEM_KO[key] || key;
}

export function itemOptions(extra: string[] = []) {
  const seen = new Set<string>();
  const out: { value: string; label: string; hint: string }[] = [];
  for (const id of [...Object.keys(ITEM_KO), ...extra]) {
    const value = id.trim().toUpperCase();
    if (!value || seen.has(value)) continue;
    seen.add(value);
    out.push({ value, label: itemNameKo(value), hint: value });
  }
  out.sort((a, b) => a.label.localeCompare(b.label, "ko"));
  return out;
}
